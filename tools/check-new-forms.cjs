const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  let saved = {};
  let readonly = false;
  let requests = 0;
  await page.route('http://naser-test.local/**', async route => {
    const name = new URL(route.request().url()).pathname.slice(1);
    let html = fs.readFileSync(path.join(root, 'formularios/operaciones', name), 'utf8');
    const setup = `<script>
      const initial = ${JSON.stringify(saved)};
      const mem = {getItem(k){return initial[k]??null},setItem(k,v){initial[k]=String(v)},__dump(){return {...initial}}};
      Object.defineProperty(window,'localStorage',{value:mem});
      window.__naserLS=mem;window.__NASER_FORM__={fields:{},readonly:${readonly}};
      window.addEventListener('message',e=>{if(e.data.type==='naser:save-request')window.testSave()});
    </script>`;
    const adapter = fs.readFileSync(path.join(root,'js/naser-collection-form.js'),'utf8');
    const bridge = fs.readFileSync(path.join(root,'js/naser-form-bridge.js'),'utf8');
    html = html.replace('<head>', '<head>'+setup).replace('</body>', `<script>${adapter}</script><script>${bridge}</script></body>`);
    await route.fulfill({contentType:'text/html', body:html});
  });
  await page.exposeFunction('testSave', () => { requests++; });
  const go = name => page.goto('http://naser-test.local/'+name);
  const state = () => page.evaluate(() => window.__naserLS.__dump());
  const collect = (validate = false) => page.evaluate(validate => new Promise(resolve => {
    const reqId = 'qa-collect';
    function receive(event) {
      if (event.data.type !== 'naser:collected' || event.data.reqId !== reqId) return;
      window.removeEventListener('message', receive);
      resolve(event.data);
    }
    window.addEventListener('message', receive);
    window.postMessage({type:'naser:collect',reqId,validate},window.location.origin);
  }), validate);
  const stockKey = 'NASER_POSN08_F1_HERRAMIENTAS_VERIFICADO_V4';
  await go('stock-herramientas.html');
  const count = JSON.parse((await state())[stockKey]).length;
  assert(count > 0, 'Original stock loaded');
  await page.click('#btnPlegarAlta');
  await page.fill('#addHerramienta','QA herramienta');
  await page.fill('#addTipo','QA tipo');
  await page.fill('#addUbicacion','QA unidad');
  await page.fill('#addVencimiento','31/02/2027');
  await page.click('#btnAgregarHerramienta');
  assert.equal(JSON.parse((await state())[stockKey]).length,count,'Reject impossible dates');
  await page.waitForTimeout(500);
  assert.equal(requests,0,'Invalid action does not request save');
  await page.fill('#addVencimiento','28/02/2027');
  await page.click('#btnAgregarHerramienta');
  await page.waitForTimeout(500);
  assert.equal(JSON.parse((await state())[stockKey]).length,count+1);
  assert.equal(requests,1,'Valid change requests save');
  await page.fill('#hsBuscar','QA herramienta');
  assert.equal(await page.locator('#hsBody tr').count(),1);
  await page.click('#hsBody [data-edit]');
  await page.fill('#edUbicacion','QA unidad editada');
  await page.click('#edGuardar');
  assert(await page.locator('#listaUnidadesNaser').innerHTML().then(s=>s.includes('QA unidad editada')));
  await page.click('#hsBody [data-edit]');
  await page.fill('#edUbicacion','QA edición desde guardar borrador');
  let collected = await collect();
  assert.equal(collected.valid,true);
  assert.equal(JSON.parse(collected.storage[stockKey])[0].ubicacion,'QA edición desde guardar borrador','Outer save includes pending edit');
  await page.click('#hsBody [data-edit]');
  await page.fill('#edVencimiento','31/02/2027');
  assert.equal((await collect()).valid,false,'Outer save rejects invalid pending edit');
  await page.fill('#edVencimiento','28/02/2027');
  await page.fill('#edUbicacion','QA unidad editada');
  assert.equal((await collect(true)).valid,true,'Submit commits a valid pending edit');
  await page.click('#tabCamion');
  await page.fill('#addCamion','QA camion nuevo');
  await page.click('#btnAgregarCamion');
  assert(await page.locator('#hsUnidad').innerHTML().then(s=>s.includes('QA camion nuevo')));
  saved = await state();
  readonly = true;
  await go('stock-herramientas.html');
  await page.waitForSelector('body.naser-readonly');
  const readonlyStock = await state();
  assert.equal(await page.locator('#hsBuscar').isEnabled(),true,'Reviewer can search');
  await page.fill('#hsBuscar','QA herramienta');
  assert.equal(await page.locator('#hsBody tr').count(),1);
  assert.equal(await page.locator('#hsBody [data-edit]').isDisabled(),true,'Rebuilt rows remain read-only');
  assert.equal(await page.locator('#hsBody [data-delete]').isDisabled(),true);
  assert.equal(await page.locator('#btnAgregarHerramienta').isDisabled(),true);
  await page.click('#hsLimpiar');
  await page.selectOption('#hsUnidad','QA unidad editada');
  assert.equal(await page.locator('#hsBody tr').count(),1);
  assert.deepEqual(await state(),readonlyStock,'Read-only filters never mutate stock');
  readonly = false;
  await go('stock-herramientas.html');
  assert.equal(JSON.parse((await state())[stockKey])[0].ubicacion,'QA unidad editada','Reopen preserves edits');
  await page.fill('#hsBuscar','QA herramienta');
  await page.click('#hsBody [data-delete]');
  assert.equal(JSON.parse((await state())[stockKey]).length,count);
  saved = {};
  await go('diagrama-trabajo.html');
  await page.click('#toggleWorkers');
  await page.fill('#wLegajo','QA001');
  await page.fill('#wNombre','Trabajador de prueba');
  await page.click('#saveWorker');
  const workersKey='naser_cronograma_trabajadores_manual_v3';
  const recordsKey='naser_cronograma_mensual_registros_v3';
  const worker=JSON.parse((await state())[workersKey])[0];
  await page.click('#toggleDay');
  await page.selectOption('#workerSelect',worker._id);
  await page.fill('#workDate','2028-02-28');
  await page.selectOption('#dayStatus','trabajo');
  await page.selectOption('#workService',{index:1});
  await page.fill('#startTime','22:00');
  await page.fill('#endTime','06:00');
  await page.fill('#consecutiveDays','3');
  await page.click('#saveDay');
  let records=JSON.parse((await state())[recordsKey]);
  assert.deepEqual(records.map(r=>r.date),['2028-02-28','2028-02-29','2028-03-01']);
  await page.selectOption('#workerSelect',worker._id);
  await page.fill('#workDate','2028-02-28');
  await page.selectOption('#dayStatus','trabajo');
  await page.selectOption('#workService',{index:1});
  await page.click('#saveDay');
  assert.equal(JSON.parse((await state())[recordsKey]).length,3,'Reject duplicate worker/day');
  saved=await state();
  await go('diagrama-trabajo.html');
  assert.equal(JSON.parse((await state())[recordsKey]).length,3,'Reopen preserves calendar');
  readonly=true;
  await go('diagrama-trabajo.html');
  await page.waitForSelector('body.naser-readonly');
  const readonlySchedule=await state();
  assert.equal(await page.locator('#monthPicker').isEnabled(),true,'Reviewer can navigate months');
  await page.fill('#monthPicker','2028-02');
  await page.locator('#monthPicker').dispatchEvent('change');
  assert.equal(await page.locator('#saveDay').isDisabled(),true);
  await page.fill('#monthPicker','2028-03');
  await page.locator('#monthPicker').dispatchEvent('change');
  assert.deepEqual(await state(),readonlySchedule,'Read-only navigation never changes schedule');
  readonly=false;
  for(const name of ['diagrama-trabajo.html','stock-herramientas.html']) {
    saved={};await go(name);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(root,'logs',name+'.png'),fullPage:true});
  }
  assert.deepEqual(errors,[],'No JavaScript errors');
  console.log('PASS: stock CRUD, pending edits, invalid dates, filters, units, save events, leap-year schedule, duplicate prevention, state recovery, read-only navigation and mobile renders.');
  if (process.env.NASER_QA_EMAIL && process.env.NASER_QA_PASSWORD) {
    const live=await browser.newPage();
    const base='http://localhost:8080';
    await live.goto(base+'/php/login.php');
    await live.fill('[name=email]',process.env.NASER_QA_EMAIL);
    await live.fill('[name=password]',process.env.NASER_QA_PASSWORD);
    await Promise.all([live.waitForURL('**/dashboard.php'),live.click('button[type=submit]')]);
    await live.goto(base+'/php/operaciones.php');
    assert.equal(await live.getByRole('link',{name:'Diagrama de trabajo',exact:true}).count(),1);
    assert.equal(await live.getByRole('link',{name:'Stock de herramientas',exact:true}).count(),1);
    for (const code of ['operaciones-diagrama-trabajo','operaciones-stock-herramientas']) {
      await live.goto(base+'/php/formularios/llenar.php?f='+code);
      const csrf=JSON.parse((await live.content()).match(/var CSRF = ("[^"]+");/)[1]);
      const api=async data => (await live.request.post(base+'/php/formularios/api.php',{headers:{'X-CSRF-Token':csrf},data})).json();
      const frame=live.frames().find(f=>f.url().includes('/render.php'));
      await frame.waitForFunction(()=>!!window.__naserLS);
      const storage=await frame.evaluate(()=>window.__naserLS.__dump());
      const result=await api({accion:'guardar',formulario:code,referencia:'QA temporal integración HTML',datos:{},storage});
      assert(result.ok,JSON.stringify(result));
      try {
        await live.goto(base+'/php/formularios/render.php?id='+result.id);
        assert.deepEqual(await live.evaluate(()=>window.__naserLS.__dump()),storage,'Database round trip');
        await live.goto(base+'/php/formularios/render.php?id='+result.id+'&solo_lectura=1');
        assert(await live.evaluate(()=>window.__NASER_FORM__.readonly),'Read-only rendering');
        const rejected=await live.request.post(base+'/php/formularios/api.php',{data:{accion:'guardar',id:result.id}});
        assert.equal(rejected.status(),403,'CSRF validation');
      } finally {
        const removed=await api({accion:'eliminar',id:result.id});
        assert(removed.ok,'Remove temporary QA record '+result.id);
      }
    }
    const guest=await browser.newContext();
    const denied=await guest.request.get(base+'/php/formularios/render.php?f=operaciones-stock-herramientas',{maxRedirects:0});
    assert.equal(denied.status(),302,'Authentication required');
    await guest.close();
    console.log('PASS: live navigation, database save/reopen for both forms, read-only mode, CSRF and authentication. Temporary records removed.');
  }
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
